package vn.svframe.fantasyhub.core;

import com.google.gson.*;
import net.fabricmc.loader.api.FabricLoader;
import java.io.*;
import java.nio.file.*;
import java.security.*;
import java.util.*;
import java.util.zip.*;

/** Installs authored data before character attachment, preserving server edits. */
final class SourcePackInstaller {
    private static final int LIMIT=16_000_000;
    private SourcePackInstaller(){}
    static boolean install() throws IOException {
        Path config=FabricLoader.getInstance().getConfigDir().toAbsolutePath().normalize();
        Path statePath=config.resolve("FantasyHub/source-pack-installation.json");
        JsonObject previous=Files.exists(statePath)?JsonParser.parseString(Files.readString(statePath)).getAsJsonObject():new JsonObject();
        Map<String,byte[]> files=new LinkedHashMap<>();long total=0;
        try(InputStream input=SourcePackInstaller.class.getResourceAsStream("/default/source-pack.zip")) {
            if(input==null)throw new IOException("Missing authored source pack in FantasyHubCore");
            try(ZipInputStream zip=new ZipInputStream(input)) {
                for(ZipEntry entry;(entry=zip.getNextEntry())!=null;) {
                    if(entry.isDirectory())continue;byte[] content=zip.readNBytes(LIMIT+1);total+=content.length;
                    if(content.length>LIMIT||total>80_000_000)throw new IOException("Source pack exceeds size limit");
                    if(files.putIfAbsent(entry.getName(),content)!=null)throw new IOException("Duplicate source pack path");
                }
            }
        }
        JsonObject manifest=JsonParser.parseString(new String(Objects.requireNonNull(files.get("manifest.json")),java.nio.charset.StandardCharsets.UTF_8)).getAsJsonObject();
        // Validate every entry before touching the existing server configuration.
        for(JsonElement raw:manifest.getAsJsonArray("files")) {
            JsonObject row=raw.getAsJsonObject();String name=row.get("path").getAsString();byte[] content=files.get(name);
            if(content==null||!sha(content).equals(row.get("sha256").getAsString()))throw new IOException("Source pack checksum mismatch: "+name);
            Path target=config.resolve(name).normalize();
            if(!target.startsWith(config)||Path.of(name).isAbsolute()||!Set.of("SVFrameMMO","SVFrameLib","SVFrameMobs","SVFrameItems","FantasyHub").contains(Path.of(name).getName(0).toString()))throw new IOException("Invalid source configuration path");
        }
        Set<String> currentNames=new HashSet<>();for(JsonElement row:manifest.getAsJsonArray("files"))currentNames.add(row.getAsJsonObject().get("path").getAsString());
        // Retire only unmodified files generated by an earlier source-pack
        // revision. This prevents obsolete imported table copies duplicating IDs.
        for(var old:previous.entrySet())if(!currentNames.contains(old.getKey())){
            Path obsolete=config.resolve(old.getKey()).normalize();
            if(obsolete.startsWith(config)&&Files.isRegularFile(obsolete)&&sha(Files.readAllBytes(obsolete)).equals(old.getValue().getAsString()))
                Files.move(obsolete,obsolete.resolveSibling(obsolete.getFileName()+".before-source-pack"),StandardCopyOption.REPLACE_EXISTING);
        }
        boolean changed=false;JsonObject next=previous.deepCopy();
        for(JsonElement raw:manifest.getAsJsonArray("files")) {
            JsonObject row=raw.getAsJsonObject();String name=row.get("path").getAsString();byte[] content=files.get(name);
            if(content==null||!sha(content).equals(row.get("sha256").getAsString()))throw new IOException("Source pack checksum mismatch: "+name);
            Path target=config.resolve(name).normalize();
            if(!target.startsWith(config)||!Set.of("SVFrameMMO","SVFrameLib","SVFrameMobs","SVFrameItems","FantasyHub").contains(Path.of(name).getName(0).toString()))throw new IOException("Invalid source configuration path");
            boolean replace=!Files.exists(target);
            if(!replace) {
                byte[] current=Files.readAllBytes(target);String hash=sha(current);
                if(hash.equals(sha(content))){next.addProperty(name,hash);continue;}
                replace=previous.has(name)&&hash.equals(previous.get(name).getAsString());
                // Fresh vanilla framework defaults are recognizable by exact
                // bytes; customized class definitions are never overwritten.
                if(!replace&&name.startsWith("SVFrameMMO/")) {
                    var module=FabricLoader.getInstance().getModContainer("svframemmo").orElseThrow();
                    var baseline=module.findPath("defaults/"+name.substring("SVFrameMMO/".length()));
                    replace=baseline.isPresent()&&Arrays.equals(current,Files.readAllBytes(baseline.get()));
                }
                if(replace)Files.copy(target,target.resolveSibling(target.getFileName()+".before-source-pack"),StandardCopyOption.REPLACE_EXISTING);
            }
            if(replace) {
                Files.createDirectories(target.getParent());Path temporary=Files.createTempFile(target.getParent(),"source-pack-",".tmp");Files.write(temporary,content);
                try{Files.move(temporary,target,StandardCopyOption.ATOMIC_MOVE,StandardCopyOption.REPLACE_EXISTING);}catch(AtomicMoveNotSupportedException ignored){Files.move(temporary,target,StandardCopyOption.REPLACE_EXISTING);}
                next.addProperty(name,sha(content));changed=true;
            }
        }
        Files.createDirectories(statePath.getParent());Path temporary=Files.createTempFile(statePath.getParent(),"installation-",".tmp");Files.writeString(temporary,new GsonBuilder().setPrettyPrinting().create().toJson(next));
        try{Files.move(temporary,statePath,StandardCopyOption.ATOMIC_MOVE,StandardCopyOption.REPLACE_EXISTING);}catch(AtomicMoveNotSupportedException ignored){Files.move(temporary,statePath,StandardCopyOption.REPLACE_EXISTING);}
        return changed;
    }
    private static String sha(byte[] bytes){try{return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));}catch(NoSuchAlgorithmException impossible){throw new IllegalStateException(impossible);}}
}
